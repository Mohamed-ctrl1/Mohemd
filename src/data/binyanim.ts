export function confusablesOf(binyan: Binyan): Binyan[] {
  const out: Binyan[] = [];
  for (const [a, b] of CONFUSION_PAIRS) {
    if (a === binyan) out.push(b);
    if (b === binyan) out.push(a);
  }
  return out;
}

