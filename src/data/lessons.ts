import { BINYAN_BY_ID, BINYAN_LABEL } from "./binyanim";
import { VERB_DATA } from "./verbs";
import type { Binyan, Topic } from "@/lib/types";

export type Block =
  | { kind: "text"; text: string }
  | { kind: "list"; items: string[] }
  | { kind: "table"; head: string[]; rows: string[][]; hebrewCols?: number[] }
  | { kind: "examples"; items: { he: string; ar: string; note?: string }[] }
  | { kind: "callout"; tone: "info" | "warn" | "tip"; title: string; text: string }
  | {
      kind: "exercise";
      items: {
        q: string;
        he?: string;
        options: string[];
        answer: string;
        hint: string;
        explanation: string;
      }[];
    };

export interface Section {
  title: string;
  blocks: Block[];
}

export interface Lesson {
  slug: string;
  title: string;
  subtitle: string;
  level: "أساسي" | "متوسط" | "متقدم";
  topics: Topic[];
  binyan?: Binyan;
  sections: Section[];
}

/** جدول التصريف لوزن معيّن، مبني مباشرة من قاعدة الأفعال المدققة. */
function conjTable(binyan: Binyan, limit = 6): Block {
  const rows = VERB_DATA.filter((v) => v.binyan === binyan)
    .slice(0, limit)
    .map((v) => [
      v.root,
      v.past3ms,
      v.present3ms,
      v.future3ms,
      v.imperative ?? "—",
      v.infinitive ?? "—",
      v.meaningAr,
    ]);
  return {
    kind: "table",
    head: ["الجذر", "עבר (הוא)", "הווה", "עתיד", "ציווי", "שם הפועל", "المعنى"],
    rows,
    hebrewCols: [0, 1, 2, 3, 4, 5],
  };
}

function examplesOf(binyan: Binyan, count = 5): Block {
  return {
    kind: "examples",
    items: VERB_DATA.filter((v) => v.binyan === binyan)
      .slice(0, count)
      .map((v) => ({ he: v.past3ms, ar: v.meaningAr, note: v.notes })),
  };
}

